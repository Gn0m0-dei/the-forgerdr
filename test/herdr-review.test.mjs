// Review rounds: a round's diff, the comments on it, and the feedback the agent gets.
const DIFF = [
  "diff --git a/src/gate.rs b/src/gate.rs",
  "index 1111111..2222222 100644",
  "--- a/src/gate.rs",
  "+++ b/src/gate.rs",
  "@@ -10,4 +10,5 @@ pub struct GateStore {",
  " pub struct GateStore {",
  "     pending: HashMap<GateId, Gate>,",
  "-    resolved: Vec<GateId>,",
  "+    resolved: HashMap<GateId, Resolution>,",
  "+    origin: Origin,",
  " }",
  "\\ No newline at end of file",
  "diff --git a/src/old name.rs b/src/new name.rs",
  "similarity index 90%",
  "rename from src/old name.rs",
  "rename to src/new name.rs",
  "--- a/src/old name.rs",
  "+++ b/src/new name.rs",
  "@@ -1 +1 @@",
  "-mod a;",
  "+mod b;",
  "diff --git a/gone.txt b/gone.txt",
  "deleted file mode 100644",
  "--- a/gone.txt",
  "+++ /dev/null",
  "@@ -1 +0,0 @@",
  "-keep",
  "diff --git a/new.txt b/new.txt",
  "new file mode 100644",
  "--- /dev/null",
  "+++ b/new.txt",
  "@@ -0,0 +1,2 @@",
  "+one",
  "+two",
  "diff --git a/logo.png b/logo.png",
  "Binary files a/logo.png and b/logo.png differ",
].join("\n");

test("a unified diff parses into files, their status and counts, hunks and numbered lines", () => {
  const { files, cut } = parseDiff(DIFF);
  strictEqual(cut, false);
  deepStrictEqual(
    files.map((file) => [
      file.path,
      file.oldPath,
      file.status,
      file.adds,
      file.dels,
      file.binary,
    ]),
    [
      ["src/gate.rs", "src/gate.rs", "M", 2, 1, false],
      ["src/new name.rs", "src/old name.rs", "R", 1, 1, false],
      ["gone.txt", "gone.txt", "D", 0, 1, false],
      ["new.txt", "new.txt", "A", 2, 0, false],
      ["logo.png", "logo.png", "M", 0, 0, true],
    ],
  );
  deepStrictEqual(
    files[0].hunks[0].header,
    "@@ -10,4 +10,5 @@ pub struct GateStore {",
  );
  deepStrictEqual(
    files[0].hunks[0].lines.map((line) => [line.kind, line.old, line.new]),
    [
      ["ctx", 10, 10],
      ["ctx", 11, 11],
      ["del", 12, null],
      ["add", null, 12],
      ["add", null, 13],
      ["ctx", 13, 14],
    ],
  );
  strictEqual(
    files[0].hunks[0].lines[3].text,
    "    resolved: HashMap<GateId, Resolution>,",
  );
});

test("a diff the bridge cut says so", () => {
  strictEqual(parseDiff(`${DIFF}\n\\ forgerdr: cut at 20000 lines`).cut, true);
  deepStrictEqual(parseDiff("").files, []);
});

/** @param {string} id @param {object} more */
const comment = (id, more) => ({
  body: `comment ${id}`,
  id,
  line: 12,
  path: "src/gate.rs",
  resolved: false,
  round: 1,
  sent: false,
  side: "new",
  text: "    resolved: HashMap<GateId, Resolution>,",
  ...more,
});

test("a comment sits on its line, follows it when code moves, is outdated once its line is removed, and is elsewhere when its line is not in this diff", () => {
  const { files } = parseDiff(DIFF);
  const anchored = anchorComments(files, [
    comment("c1", {}),
    comment("c2", { line: 40 }),
    comment("c3", { text: "    resolved: Vec<GateId>," }),
    comment("c4", {
      line: 12,
      side: "old",
      text: "    resolved: Vec<GateId>,",
    }),
    comment("c5", { path: "src/other.rs" }),
    comment("c6", { line: 30, text: "    fn untouched() {}" }),
  ]);
  deepStrictEqual(
    [...anchored.placed.keys()],
    ["src/gate.rs:new:12", "src/gate.rs:old:12"],
  );
  deepStrictEqual(
    anchored.placed.get("src/gate.rs:new:12")?.map((one) => one.id),
    ["c1", "c2"],
  );
  deepStrictEqual(
    anchored.outdated.map((one) => one.id),
    ["c3"],
  );
  deepStrictEqual(
    anchored.elsewhere.map((one) => one.id),
    ["c5", "c6"],
  );
});

test("the feedback quotes each comment's file, line and code, for the agent to answer each", () => {
  strictEqual(
    feedbackOf(2, [
      comment("c1", { body: "Return the gate's origin too." }),
      comment("c4", {
        body: "Why drop the Vec?",
        line: 12,
        side: "old",
        text: "    resolved: Vec<GateId>,",
      }),
    ]),
    [
      "Review of round 2: 2 comments on your changes. Address each one, then reply to each in a line.",
      "",
      "1. src/gate.rs:12",
      "   > resolved: HashMap<GateId, Resolution>,",
      "   Return the gate's origin too.",
      "",
      "2. src/gate.rs:12 (a removed line)",
      "   > resolved: Vec<GateId>,",
      "   Why drop the Vec?",
    ].join("\n"),
  );
  strictEqual(
    feedbackOf(1, [comment("c1", { body: "One." })]).split("\n")[0],
    "Review of round 1: 1 comment on your changes. Address it, then reply in a line.",
  );
});

test("the round's rows: a header per file, then its hunks and lines and the comments under their line", () => {
  const { files } = parseDiff(DIFF);
  const anchored = anchorComments(files, [comment("c1", {})]);
  const rows = diffRows(files, {
    collapsed: new Set(["src/new name.rs", "gone.txt", "new.txt", "logo.png"]),
    composing: { line: 10, path: "src/gate.rs", side: "new" },
    outdated: [],
    placed: anchored.placed,
  });
  deepStrictEqual(
    rows.map((row) => row.kind),
    [
      "file",
      "hunk",
      "line",
      "compose",
      "line",
      "line",
      "line",
      "comments",
      "line",
      "line",
      "file",
      "file",
      "file",
      "file",
    ],
  );
  strictEqual(new Set(rows.map((row) => row.key)).size, rows.length);
  deepStrictEqual(
    rows.slice(1, 4).map((row) => row.key),
    [
      "hunk:src/gate.rs:@@ -10,4 +10,5 @@ pub struct GateStore {",
      "line:src/gate.rs:10:10",
      "compose:src/gate.rs:new:10",
    ],
  );
});

test("feedback goes only to an agent at its prompt, never to a shell or a dialog", () => {
  const claude = { agent: true, name: "claude" };
  strictEqual(sendableTo({ program: claude, status: "idle" }), true);
  strictEqual(sendableTo({ program: claude, status: "working" }), true);
  strictEqual(sendableTo({ program: claude, status: "blocked" }), false);
  strictEqual(
    sendableTo({ program: { name: "zsh", shell: true }, status: null }),
    false,
  );
  strictEqual(sendableTo(undefined), false);
});

test("the feedback carries no control characters, only lines", () => {
  const prompt = feedbackOf(1, [
    comment("c1", {
      body: "fix\u001b[201~\r!touch y\r",
      text: "x\u0007 = 1;\u009b",
    }),
  ]);
  strictEqual([...prompt].some(isControl), false);
  strictEqual(prompt.includes("fix[201~!touch y"), true);
});

test("the review closes its tab only when the tab holds the view alone and is not its space's last", () => {
  const view = { pane: "p1", tab: "tb-42", terminal: null };
  const spaces = [{ id: "sp1", tabs: [{ id: "tb-1" }, { id: "tb-42" }] }];
  strictEqual(closableReviewTab("tb-42", [view], spaces), true);
  strictEqual(
    closableReviewTab(
      "tb-42",
      [view, { pane: "p2", tab: "tb-42", terminal: "t3" }],
      spaces,
    ),
    false,
  );
  strictEqual(
    closableReviewTab(
      "tb-42",
      [view],
      [{ id: "sp1", tabs: [{ id: "tb-42" }] }],
    ),
    false,
  );
  strictEqual(closableReviewTab("", [view], spaces), false);
});

test("a review's session is done once idle or done, or gone, never while it works or waits on the human", () => {
  strictEqual(turnOver({ address: "t7", state: "live", status: "idle" }), true);
  strictEqual(turnOver({ address: "t7", state: "live", status: "done" }), true);
  strictEqual(
    turnOver({ address: "t7", state: "finished", status: "working" }),
    true,
  );
  strictEqual(turnOver(undefined), true);
  strictEqual(
    turnOver({ address: "t7", state: "live", status: "working" }),
    false,
  );
  strictEqual(
    turnOver({ address: "t7", state: "live", status: "blocked" }),
    false,
  );
});
