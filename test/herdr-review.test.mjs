/** @param {string} id @param {string} terminal @param {string} header @param {number} created */
const request = (id, terminal, header, created) => ({
  agent_type: "",
  created,
  cwd: "/r",
  id,
  kind: header.startsWith("Gate ") ? "gate" : "question",
  session_id: "s",
  terminal,
  tool_input: {
    questions: [
      {
        header,
        options: [{ label: "a" }, { label: "b" }],
        question: `${header}?`,
      },
    ],
  },
  tool_name: "AskUserQuestion",
});

const DRAFT = {
  body: "x",
  id: "1",
  locations: [{ line: 1, path: "a.rs" }],
  resolve: false,
  suggestion: "",
};
const REVIEW = {
  drafted: 0,
  drafts: [DRAFT],
  results: [],
  session: "s",
  stamped: null,
};

test("the view answers its own agent's pick and comment gate, and nothing else", () => {
  const requests = [
    request("a", "t8", "Review pick", 1),
    request("b", "t7", "Gate commit", 2),
    request("c", "t7", "Review pick", 3),
  ];
  deepStrictEqual(
    [
      pendingAsk(requests, "t7", REVIEW)?.kind,
      pendingAsk(requests, "t7", REVIEW)?.request.id,
    ],
    [ASK.pick, "c"],
  );
  strictEqual(
    pendingAsk([request("d", "t7", "Gate comment", 4)], "t7", REVIEW)?.kind,
    ASK.gate,
  );
  strictEqual(pendingAsk(requests.slice(1, 2), "t7", REVIEW), null);
});

test("the view answers a comment gate only when it was asked for the drafts it shows", () => {
  const gate = (/** @type {number} */ created) => [
    request("g", "t7", "Gate comment", created),
  ];
  const review = { ...REVIEW, drafted: 10 };
  const published = {
    action: "",
    commit: "",
    id: "1",
    line: 1,
    path: "a.rs",
    reason: "",
    status: "published",
    url: "",
  };
  strictEqual(pendingAsk(gate(12), "t7", review)?.kind, ASK.gate);
  strictEqual(pendingAsk(gate(5), "t7", review), null);
  strictEqual(
    pendingAsk(gate(12), "t7", { ...review, drafts: [] })?.kind,
    ASK.gate,
  );
  strictEqual(
    pendingAsk(gate(12), "t7", { ...review, results: [published] }),
    null,
  );
  strictEqual(
    pendingAsk(gate(12), "t7", {
      ...review,
      stamped: { at: 15, drafts: [DRAFT] },
    })?.kind,
    ASK.gate,
  );
  strictEqual(
    pendingAsk(gate(20), "t7", {
      ...review,
      stamped: { at: 15, drafts: [DRAFT] },
    }),
    null,
  );
  strictEqual(pendingAsk(gate(12), "t7", null), null);
});

test("the view answers a comment gate only from the session that made the review", () => {
  const gate = [request("g", "t7", "Gate comment", 12)];
  const other = [
    { ...request("h", "t7", "Gate comment", 12), session_id: "resumed" },
  ];
  strictEqual(pendingAsk(gate, "t7", REVIEW)?.kind, ASK.gate);
  strictEqual(pendingAsk(other, "t7", REVIEW), null);
  strictEqual(pendingAsk(gate, "t7", { ...REVIEW, session: "" }), null);
  strictEqual(
    pendingAsk(gate, "t7", { ...REVIEW, session: "" }, "s")?.kind,
    ASK.gate,
  );
});

