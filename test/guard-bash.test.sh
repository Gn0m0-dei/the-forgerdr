#!/usr/bin/env bash
# Smallest check that fails if guard-bash.sh breaks. Run: bash test/guard-bash.test.sh
set -euo pipefail
hook="$(cd "$(dirname "$0")/.." && pwd)/hooks/guard-bash.sh"
sandbox="$(mktemp -d)"
trap 'rm -rf "$sandbox"' EXIT

failures=0
expect() {
  if [ "$2" = "$3" ]; then printf 'ok   %s\n' "$1"; else printf 'FAIL %s\n  expected: %s\n  actual:   %s\n' "$1" "$2" "$3"; failures=$((failures + 1)); fi
}
run() { printf '%s' "$1" | jq -Rs '{tool_input:{command:.}}' | bash "$hook"; }
decision() { run "$1" | jq -r '.hookSpecificOutput.permissionDecision // empty'; }

rewritten() { run "$1" | jq -r '.hookSpecificOutput.updatedInput.command // empty'; }

# shellcheck disable=SC2016 # the command substitution must reach the hook unexpanded
heredoc='git commit -m "$(cat <<'"'"'EOF'"'"'
feat: x

Co-Authored-By: Claude Fable 5.1 <noreply@anthropic.com>
EOF
)"'
# shellcheck disable=SC2016
expect "heredoc trailer stripped" "$(printf 'git commit -m "$(cat <<'"'"'EOF'"'"'\nfeat: x\n\nEOF\n)"')" "$(rewritten "$heredoc")"
expect "heredoc not denied" "" "$(decision "$heredoc")"
multiline=$'git commit -m "feat: x\n\nCo-Authored-By: Claude <noreply@anthropic.com>"'
expect "closing quote kept" $'git commit -m "feat: x\n\n"' "$(rewritten "$multiline")"
body=$'gh pr create --title "feat: x" --body "Done.\n\n🤖 Generated with [Claude Code](https://claude.com/claude-code)"'
expect "pr body robot line stripped" $'gh pr create --title "feat: x" --body "Done.\n\n"' "$(rewritten "$body")"
expect "clean command not rewritten" "" "$(rewritten 'git commit -m "feat: add login"')"
expect "rewrite keeps the rest of the input" "x" "$(printf '%s' "$multiline" | jq -Rs '{tool_input:{command:.,description:"x"}}' | bash "$hook" | jq -r '.hookSpecificOutput.updatedInput.description')"

expect "existing denial kept" deny "$(decision 'git reset --hard HEAD~1')"
expect "plain commit passes" "" "$(decision 'git commit -m "feat: add login"')"
expect "amend without message passes" "" "$(decision 'git commit --amend --no-edit')"
expect "grep mentioning a trailer passes" "" "$(decision 'grep -rn "Co-Authored-By: Claude" .')"
expect "inline trailer denied" deny "$(decision 'git commit -m "feat: x" -m "Co-Authored-By: Claude <noreply@anthropic.com>"')"
expect "robot in title denied" deny "$(decision 'gh pr create --title "🤖 feat: x" --body "done"')"
expect "generated by vendor denied" deny "$(decision 'glab mr create --description "Generated by Copilot" --title "x"')"
expect "generator tool passes" "" "$(decision 'git commit -m "chore: client generated by openapi-generator"')"
expect "subject mentioning a trailer without a bot address passes" "" "$(decision 'git commit -m "fix: drop Co-Authored-By: Claude from the template"')"
printf 'feat: x\n\nCo-Authored-By: Claude <noreply@anthropic.com>\n' > "$sandbox/msg"
expect "trailer inside -F file denied" deny "$(decision "git commit -F $sandbox/msg")"
expect "trailer inside --body-file denied" deny "$(decision "gh pr create --body-file=$sandbox/msg --title x")"
expect "git -C before commit still checked" deny "$(decision 'git -C /tmp/x commit -m "feat: x" -m "Co-Authored-By: Claude <noreply@anthropic.com>"')"
expect "git -c before commit still stripped" $'git -c user.name=x commit -m "feat: x\n\n"' "$(rewritten $'git -c user.name=x commit -m "feat: x\n\nCo-Authored-By: Claude <noreply@anthropic.com>"')"
expect "quoted -F path read" deny "$(decision "git commit -F \"$sandbox/msg\"")"
expect "single-quoted --body-file read" deny "$(decision "gh pr create --body-file '$sandbox/msg' --title x")"
expect "human co-author named Devin passes" "" "$(run $'git commit -m "feat: x\n\nCo-Authored-By: Devin Smith <devin@corp.com>"')"
expect "human co-author named Claude passes" "" "$(run $'git commit -m "feat: x\n\nCo-Authored-By: Claude Dupont <claude@dupont.fr>"')"
expect "vendor inside a longer word passes" "" "$(decision 'git commit -m "chore: generated by codexgen"')"
expect "copilot bot trailer denied" deny "$(decision 'git commit -m "feat: x" -m "Co-authored-by: Copilot <223556219+Copilot@users.noreply.github.com>"')"
expect "devin bot trailer denied" deny "$(decision 'git commit -m "feat: x" -m "Co-authored-by: devin-ai-integration[bot] <158243242+devin-ai-integration[bot]@users.noreply.github.com>"')"
expect "signed-off noreply anthropic stripped" $'git commit -m "feat: x\n\n"' "$(rewritten $'git commit -m "feat: x\n\nSigned-off-by: Claude <noreply@anthropic.com>"')"
expect "stripped lines reported" "forgerdr guard: stripped from the command: Co-Authored-By: Claude <noreply@anthropic.com>" "$(run "$multiline" | jq -r '.hookSpecificOutput.additionalContext')"
expect "--no-pager before commit checked" deny "$(decision 'git --no-pager commit -m "feat: x" -m "Co-Authored-By: Claude <noreply@anthropic.com>"')"
expect "quoted -c value before commit checked" deny "$(decision 'git -c user.name="John Doe" commit -m "feat: x" -m "Co-Authored-By: Claude <noreply@anthropic.com>"')"
expect "--git-dir and --work-tree before commit checked" deny "$(decision 'git --git-dir=/x/.git --work-tree /x commit -m "feat: x" -m "Co-Authored-By: Claude <noreply@anthropic.com>"')"
expect "absolute git path checked" deny "$(decision '/usr/bin/git commit -m "feat: x" -m "Co-Authored-By: Claude <noreply@anthropic.com>"')"
expect "glued -F path read" deny "$(decision "git commit -F$sandbox/msg")"
cp "$sandbox/msg" "$sandbox/my msg"
expect "escaped space in -F path read" deny "$(decision "git commit -F $sandbox/my\\ msg")"
expect "relative -F resolved against cwd" deny "$(printf '%s' 'git commit -F msg' | jq -Rs --arg cwd "$sandbox" '{cwd:$cwd,tool_input:{command:.}}' | bash "$hook" | jq -r '.hookSpecificOutput.permissionDecision // empty')"
expect "az body with vendor denied" deny "$(decision 'az repos pr create --description "🤖 Generated with [Claude Code](https://claude.com/claude-code)"')"

[ "$failures" -eq 0 ] || { printf '%s failure(s)\n' "$failures"; exit 1; }
printf 'all good\n'
